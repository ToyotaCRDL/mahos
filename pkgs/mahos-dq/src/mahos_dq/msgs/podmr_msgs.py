class MWMode(Message, enum.Enum):
    """MW Control Mode."""

    QPSK = 0  # 4-phase control using SG IQ modulation from digital source (PG).
    Ext2Phase = 1  # 2-phase control using external 90-deg splitter and two switches.
    ArbPhase = 2  # Arbitrary phase control using SG IQ modulation from analog source (AWG).
    AWG = 10  # MW directly generated by an AWG.

    @classmethod
    def parse(cls, mode: MWMode | str | int) -> MWMode:
        if isinstance(mode, cls):
            return mode
        if isinstance(mode, int) and not isinstance(mode, bool):
            return cls(mode)
        elif not isinstance(mode, str):
            raise TypeError("mode must be MWMode, int, or str")
        m = mode.lower().strip().replace("_", "-")
        if m in ("qpsk", "0"):
            return cls.QPSK
        if m in ("ext2phase", "ext-2phase", "ext-2-phase", "1"):
            return cls.Ext2Phase
        if m in ("arbphase", "arb-phase", "2"):
            return cls.ArbPhase
        if m in ("awg", "10"):
            return cls.AWG
        raise ValueError(f"Unrecognized mode string: {mode}")


def is_sweepN(method: str) -> bool:
    return method in ("cpN", "cpmgN", "xy4N", "xy8N", "xy16N", "ddgateN", "xy8clNflip")


def is_CPlike(method: str) -> bool:
    return method in (
        "cp",
        "cpN",
        "cpmg",
        "cpmgN",
        "xy4",
        "xy4N",
        "xy8",
        "xy8N",
        "xy16",
        "xy16N",
        "ddgate",
        "ddgateN",
        "rcp",
        "rxy4",
        "rxy8",
        "rxy16",
    )


def is_correlation(method: str) -> bool:
    return method in ("xy8cl", "xy8cl1flip", "xy8clNflip")


class PODMRData(BasicMeasData):
    """Pulse ODMR data container with TDC-derived raw traces.

    :ivar tdc_status: Latest time-to-digital-converter status summary.
    :ivar data0: Accumulated signal data for pattern 0.
    :ivar data1: Accumulated signal data for pattern 1.
    :ivar data2: Accumulated signal data for pattern 2.
    :ivar data3: Accumulated signal data for pattern 3.
    :ivar data0ref: Reference data for pattern 0.
    :ivar data1ref: Reference data for pattern 1.
    :ivar data2ref: Reference data for pattern 2.
    :ivar data3ref: Reference data for pattern 3.
    :ivar raw_data: Raw detector events or histogram data.
    :ivar raw_xdata: X-axis for ``raw_data``.
    :ivar marker_indices: Cached marker ranges for signal/reference windows.
    :ivar laser_timing: Pulse timing array used for ROI calculation.

    Pattern-indexed access is provided by ``data(index)`` / ``data_ref(index)``
    and ``set_data(index, value)`` / ``set_data_ref(index, value)``.

    """

    def __init__(self, params: dict | None = None, label: str = ""):
        self.set_version(8)
        self.init_params(params, label)
        self.init_attrs()

        self.init_xdata()

        self.tdc_status: TDCStatus | None = None

        self.data0 = None
        self.data1 = None
        self.data2 = None
        self.data3 = None
        self.data0ref = None
        self.data1ref = None
        self.data2ref = None
        self.data3ref = None

        self.raw_data = None
        self.raw_xdata = None

        self.marker_indices = None
        self.laser_timing = None
        self.laser_timing_offset = None

    def _get_pattern_data(self, i: int):
        return getattr(self, f"data{i}", None)

    def _set_pattern_data(self, i: int, val):
        setattr(self, f"data{i}", val)

    def _get_pattern_ref(self, i: int):
        return getattr(self, f"data{i}ref", None)

    def _set_pattern_ref(self, i: int, val):
        setattr(self, f"data{i}ref", val)

    @staticmethod
    def _check_pattern_index(index: int):
        if not 0 <= index < 4:
            raise IndexError(f"index {index} out of range for pattern data")

    def data(self, index: int) -> np.ndarray | None:
        """Get analyzed signal data at ``index``."""

        self._check_pattern_index(index)
        return self._get_pattern_data(index)

    def data_ref(self, index: int) -> np.ndarray | None:
        """Get analyzed reference data at ``index``."""

        self._check_pattern_index(index)
        return self._get_pattern_ref(index)

    def set_data(self, index: int, value):
        """Set analyzed signal data at ``index``."""

        self._check_pattern_index(index)
        self._set_pattern_data(index, value)

    def set_data_ref(self, index: int, value):
        """Set analyzed reference data at ``index``."""

        self._check_pattern_index(index)
        self._set_pattern_ref(index, value)

    def init_xdata(self):
        if not self.has_params():
            # dummy xdata
            self.xdata = np.arange(101) * 1e-9
            return

        # xdata is N (not tau)
        if self.is_sweepN():
            i = np.arange(self.params["Nnum"], dtype=np.int64)
            self.xdata = self.params["Nstart"] + i * self.params["Nstep"]
        else:
            # supersampling
            if self.is_supersampling():
                i = np.arange(self.params["num"])
                pulse_num = {"xy8": 8, "xy16": 16}[self.label] * self.params["pulse"]["Nconst"]
                sample = np.linspace(0, 1, num=self.params["pulse"]["supersample"] + 1)
                i_sub = (sample * pulse_num).astype(np.int64)[:-1] / pulse_num

                i = np.array([i_sub + j for j in i]).reshape(len(i) * len(i_sub))
                self.xdata = self.params["start"] + i * self.params["step"]

            # xlog
            elif self.params["log"]:
                start = np.log10(self.params["start"])
                stop = np.log10(
                    self.params["start"] + (self.params["num"] - 1) * self.params["step"]
                )
                x = np.logspace(start, stop, self.params["num"])
                if (self.params["start"] >= 1e-6) and (self.params["step"] >= 1e-6):
                    self.xdata = (x * 1e9 / 10).astype(np.int64) * 10 / 1e9  # round in [10 ns]
                else:
                    self.xdata = (x * 1e9).astype(np.int64) / 1e9  # round in [ns]

            # normal
            else:
                i = np.arange(self.params["num"])
                self.xdata = self.params["start"] + i * self.params["step"]

        if self.params.get("invert_sweep", False):
            self.xdata = self.xdata[::-1]

    # h5

    def _h5_write_tdc_status(self, val):
        return np.array(val)

    def _h5_read_tdc_status(self, val):
        if len(val) == 5:
            # older version had 5 values
            return TDCStatus(val[0], *val[2:])
        return TDCStatus(*val)

    def _h5_write_fit_params(self, val):
        d = val.copy()
        if "peak_type" in d:
            d["peak_type"] = d["peak_type"].value
        return np.void(msgpack.dumps(d))

    def _h5_read_fit_params(self, val):
        d = msgpack.loads(val.tobytes())
        if "peak_type" in d:
            d["peak_type"] = PeakType(d["peak_type"])
        return d

    def _h5_attr_writers(self) -> dict:
        return {
            "fit_params": self._h5_write_fit_params,
            "fit_result": self._h5_write_fit_result,
            "tdc_status": self._h5_write_tdc_status,
        }

    def _h5_readers(self) -> dict:
        return {
            "fit_params": self._h5_read_fit_params,
            "fit_result": self._h5_read_fit_result,
            "tdc_status": self._h5_read_tdc_status,
        }

    # getters

    def get_bin(self) -> float | None:
        """Get TDC time bin in sec."""

        try:
            return self.params["instrument"]["tbin"]
        except (KeyError, TypeError):
            return None

    def get_range(self) -> float | None:
        """Get TDC sweep range in sec."""

        try:
            return self.params["instrument"]["trange"]
        except (KeyError, TypeError):
            pass

        # fallback to tbin * len(raw_data) (only works in no-ROI mode)
        if self.has_roi():
            return None
        tbin = self.get_bin()
        data = self.raw_data
        if tbin is None or data is None:
            return None
        return tbin * len(data)

    def get_roi_margins(self) -> tuple[float, float]:
        """ROI margins [head, tail] in sec."""

        return (self.params.get("roi_head", -1.0e-9), self.params.get("roi_tail", -1.0e-9))

    def get_roi_num(self) -> int:
        """Get number of points in a ROI."""

        margin_head, margin_tail = self.get_roi_margins()
        return round((self.params["laser_width"] + margin_head + margin_tail) / self.get_bin())

    def get_roi(self, index: int) -> tuple[int, int]:
        """Get ROI (start, stop) at `index` in unit of time bins."""

        head, _ = self.get_roi_margins()
        start = round((self.laser_timing[index] - head) / self.get_bin())
        stop = start + self.get_roi_num()
        return start, stop

    def get_rois(self) -> list[tuple[int, int]]:
        """Get list of ROI (start, stop) in unit of time bins for all the laser pulses."""

        head, _ = self.get_roi_margins()
        num = self.get_roi_num()
        rois = []
        for t in self.laser_timing:
            start = round((t - head) / self.get_bin())
            rois.append((start, start + num))
        return rois

    def get_raw_xdata(self) -> np.ndarray | list[np.ndarray] | None:
        """Get x (time) axis of raw data.

        if roi is enabled, returns list of ndarray for each laser pulses.
        if roi is disabled, returns single ndarray.

        """

        if self.raw_xdata is not None:
            return self.raw_xdata

        if (self.raw_data is None) or ("instrument" not in self.params):
            return None

        if not self.has_roi():
            self.raw_xdata = np.arange(len(self.raw_data)) * self.get_bin()
            return self.raw_xdata
        else:
            self.raw_xdata = []
            for i in range(len(self.laser_timing)):
                start, stop = self.get_roi(i)
                num = stop - start
                self.raw_xdata.append((np.arange(num) + start) * self.get_bin())
            return self.raw_xdata

    def get_fit_xdata(self) -> NDArray | None:
        return self.get_xdata(fit=True)

    def _concat_xdata(self, xdata):
        if not self.is_partial() and self.params["plot"]["plotmode"] == "concatenate":
            N = self.num_pattern()
            # Complementary concatenate mode currently supports only N=2 and N=4.
            if N not in (2, 4):
                raise ValueError(f"unsupported num_pattern {N} for concatenate")
            xdata = np.repeat(xdata, N)
        return xdata

    def get_total_scale(self):
        """Get the scaling parameters to get total precession time.

        :returns: (a, b) where total precession time is a * raw_xdata + b

        """

        m = self.get_method()
        pp = self.get_pulse_params()
        a, b = 1, 0
        if m == "spinecho":
            a = 2
        elif m == "trse":
            b = pp["tauconst"]
        elif m in ["cp", "cpmg", "ddgate", "rcp"]:
            a = 2 * pp["Nconst"]
        elif m in ["xy4", "rxy4"]:
            a = 2 * pp["Nconst"] * 4
        elif m in ["xy8", "rxy8"]:
            a = 2 * pp["Nconst"] * 8
        elif m in ["xy16", "rxy16"]:
            a = 2 * pp["Nconst"] * 16

        elif m in ["cpN", "cpmgN"]:
            a = 2 * pp["tauconst"]
        elif m == "xy4N":
            a = 2 * pp["tauconst"] * 4
        elif m == "xy8N":
            a = 2 * pp["tauconst"] * 8
        elif m == "xy16N":
            a = 2 * pp["tauconst"] * 16

        elif m == "xy8cl":
            a = 1
        elif m == "xy8cl1flip":
            a = 2
            b = pp["180pulse"]
        elif m == "xy8clNflip":
            a = 2 * pp["tauconst"] + pp["180pulse"]
            b = 0
        else:
            raise ValueError(f"invalid method {m} for taumode == total")

        return a, b

    def _get_xdata_total(self, xdata):
        a, b = self.get_total_scale()
        return a * xdata + b

    def _get_xdata_freq(self, xdata):
        m = self.get_method()
        if self.is_CPlike() and not self.is_sweepN():
            pi = self.get_pulse_params()["180pulse"]
            # freq = 1 / (4 * tau + 2 * 180pulse)
            return 1 / (xdata * 4 + pi * 2)
        elif m == "spinecho":
            pi = self.get_pulse_params()["180pulse"]
            # freq = 1 / (2 * tau + 180pulse)
            return 1 / (xdata * 2 + pi)
        else:
            raise ValueError(f"invalid method {m} for taumode == freq")

    def _get_xdata_head(self, xdata):
        signal_head = self.marker_indices[0]
        tbin = self.params["instrument"]["tbin"]
        if self.is_partial():
            return signal_head * tbin
        if self.params["plot"]["plotmode"] == "concatenate":
            return signal_head * tbin
        else:
            return signal_head[0 : len(xdata) * self.num_pattern() : self.num_pattern()] * tbin

    def get_xdata(self, fit=False, force_taumode: str = "") -> NDArray | None:
        """Get analyzed xdata.

        :returns: if data is not ready, None is returned.
        :raises ValueError: when taumode is unknown or method is invalid for given taumode.

        """

        if fit:
            xdata = self.fit_xdata
        else:
            xdata = self.xdata
        if xdata is None:
            return None

        taumode = force_taumode or self.params["plot"]["taumode"]
        if taumode == "raw":
            return self._concat_xdata(xdata)
        elif taumode == "total":
            return self._concat_xdata(self._get_xdata_total(xdata))
        elif taumode == "freq":
            return self._concat_xdata(self._get_xdata_freq(xdata))
        elif taumode == "index":
            return self._concat_xdata(np.arange(len(xdata)))
        elif taumode == "head":
            if fit:  # not for fit
                return None
            return self._get_xdata_head(xdata)
        else:
            raise ValueError(f"unknown taumode {taumode}")

    def get_fit_ydata(self):
        return self.fit_data

    def get_ydata(self) -> tuple[NDArray | None, NDArray | None]:
        """Get analyzed ydata.

        :returns: (ydata0, ydata1) if two types of data are available.
                  (ydata, None) if only one type of data is available.
                  (None, None) if data is not ready.
        :raises ValueError: when mode is unknown.

        """

        if not self.has_data():
            return None, None

        if self.is_partial():
            return self._get_ydata_partial()
        else:
            return self._get_ydata_complementary()

    def _get_ydata_partial(self):
        p = self.partial()
        if p is None or p < 0:
            return None, None
        if p >= self.num_pattern():
            raise ValueError(f"invalid partial {p} for num_pattern {self.num_pattern()}")

        data = self._get_pattern_data(p)
        ref = self._get_pattern_ref(p)

        refmode = self.params["plot"]["refmode"]
        if refmode == "subtract":
            s = data - ref
        elif refmode == "divide":
            s = data / ref
        elif refmode == "ignore":
            s = data
        else:
            raise ValueError(f"unknown refmode {refmode}")

        plotmode = self.params["plot"]["plotmode"]
        if plotmode == "ref":
            return ref, None
        else:  # other plotmode is ignored
            return s, None

    def _get_ydata_complementary(self):
        """Get complementary-mode ydata.

        Current user-facing complementary plotting is intentionally limited to
        2-pattern and 4-pattern data. Other pattern counts are rejected.

        """

        N = self.num_pattern()
        if N == 2:
            return self._get_ydata_complementary_n2()
        if N == 4:
            return self._get_ydata_complementary_n4()
        raise ValueError(f"unsupported num_pattern {N} for complementary mode")

    def _linear_bg(self, y):
        if len(y) == 1:
            return np.zeros_like(y)
        x = self.get_xdata()
        try:
            p = Polynomial.fit(x, y, 1)
            b, a = p.convert().coef
            return a * x + b
        except (TypeError, ValueError, np.linalg.LinAlgError) as e:
            print(f"error in Polynomial.fit: {e}")
            return np.zeros_like(y)

    def _get_ydata_complementary_n2(self):
        s0_raw = self._get_pattern_data(0)
        s1_raw = self._get_pattern_data(1)
        r0_raw = self._get_pattern_ref(0)
        r1_raw = self._get_pattern_ref(1)
        if s0_raw is None or s1_raw is None or r0_raw is None or r1_raw is None:
            return None, None

        if self.params["plot"]["refaverage"]:
            r01 = np.mean((r0_raw, r1_raw))
            r0, r1 = r01, r01
        else:
            r0, r1 = r0_raw, r1_raw

        refmode = self.params["plot"]["refmode"]
        if refmode == "subtract":
            s0 = s0_raw - r0
            s1 = s1_raw - r1
        elif refmode == "divide":
            s0 = s0_raw / r0
            s1 = s1_raw / r1
        elif refmode == "ignore":
            s0 = s0_raw
            s1 = s1_raw
        else:
            raise ValueError(f"unknown refmode {refmode}")

        plotmode = self.params["plot"]["plotmode"]
        flip = self.params["plot"].get("flipY", False)
        if plotmode == "data01":
            return s0, s1
        elif plotmode == "data0":
            return s0, None
        elif plotmode == "data1":
            return s1, None
        elif plotmode == "diff":
            if flip:
                return s1 - s0, None
            else:
                return s0 - s1, None
        elif plotmode == "average":
            return (s0 + s1) / 2, None
        elif plotmode == "normalize":
            if flip:
                return (s1 - s0) / (s0 + s1) * 2, None
            else:
                return (s0 - s1) / (s0 + s1) * 2, None
        elif plotmode == "linear-bg0":
            bg = self._linear_bg(s0)
            return s0 - bg, s1 - bg
        elif plotmode == "linear-bg1":
            bg = self._linear_bg(s1)
            return s0 - bg, s1 - bg
        elif plotmode == "concatenate":
            return np.column_stack((s0, s1)).reshape(len(s0) * 2), None
        elif plotmode == "ref":
            return r0_raw, r1_raw
        else:
            raise ValueError(f"unknown plotmode {plotmode}")

    def _get_ydata_complementary_n4(self):
        s_raw = [self._get_pattern_data(i) for i in range(4)]
        r_raw = [self._get_pattern_ref(i) for i in range(4)]
        if any(v is None for v in s_raw + r_raw):
            return None, None

        if self.params["plot"]["refaverage"]:
            r_mean = np.mean(tuple(r_raw))
            r = [r_mean, r_mean, r_mean, r_mean]
        else:
            r = r_raw

        refmode = self.params["plot"]["refmode"]
        if refmode == "subtract":
            s = [si - ri for si, ri in zip(s_raw, r)]
        elif refmode == "divide":
            s = [si / ri for si, ri in zip(s_raw, r)]
        elif refmode == "ignore":
            s = list(s_raw)
        else:
            raise ValueError(f"unknown refmode {refmode}")

        s0, s1, s2, s3 = s

        plotmode = self.params["plot"]["plotmode"]
        flip = self.params["plot"].get("flipY", False)
        if plotmode == "data01":
            return s0, s1
        elif plotmode == "data23":
            return s2, s3
        elif plotmode == "data0":
            return s0, None
        elif plotmode == "data1":
            return s1, None
        elif plotmode == "data2":
            return s2, None
        elif plotmode == "data3":
            return s3, None
        elif plotmode == "diff":
            y = s0 - s1 + s2 - s3
            if flip:
                y = -y
            return y, None
        elif plotmode == "diff01-23":
            if flip:
                return s1 - s0, s3 - s2
            else:
                return s0 - s1, s2 - s3
        elif plotmode == "average":
            return (s0 + s1 + s2 + s3) / 4, None
        elif plotmode == "ref01":
            return r_raw[0], r_raw[1]
        elif plotmode == "ref23":
            return r_raw[2], r_raw[3]
        elif plotmode == "concatenate":
            return np.column_stack((s0, s1, s2, s3)).reshape(len(s0) * 4), None
        elif plotmode in ("normalize", "ref"):
            raise ValueError(f"plotmode {plotmode} is unsupported for num_pattern=4")
        else:
            raise ValueError(f"unknown plotmode {plotmode}")

    def get_sampling_rate(self) -> tuple[float, float]:
        signal_head = self.marker_indices[0]
        N = self.num_pattern()
        if len(signal_head) <= 1:
            return 0.0, 0.0
        dt = (signal_head[1] - signal_head[0]) * self.params["instrument"]["tbin"]
        total = dt * N * len(self.xdata)
        return dt, total

    def get_params(self) -> dict:
        if not self.has_params():
            return {}
        p = self.params.copy()
        p["pulse"] = self.get_pulse_params()
        return p

    def get_pulse_params(self) -> dict:
        if not self.has_params():
            return {}
        pp = self.params["pulse"]
        if not ("90pulse" in pp and ("180pulse" in pp or "270pulse" in pp)):
            return pp.copy()

        p90 = pp["90pulse"]
        p = pp.copy()

        if "180pulse" in pp:
            p180 = pp["180pulse"]
            if p180 <= 0:
                p180 = p90 * 2
            p["180pulse"] = p180

        if "270pulse" in pp:
            p270 = pp["270pulse"]
            if p270 <= 0:
                p270 = p90 * 3
            p["270pulse"] = p270

        return p

    def get_method(self) -> str | None:
        if not self.has_params():
            return None
        return self.label

    def snapshot_for_save(self, finalize: bool = False) -> PODMRData:
        """Make a save-ready snapshot without mutating this instance.

        The snapshot is shallow by design so large arrays (for example ``raw_data``)
        are not duplicated.
        This relies on save running in the node thread (non-async) where concurrent
        mutation during serialization does not occur.

        :param finalize: Finalize the snapshot when ``True`` and
            this data has not already been finalized.

        """

        d = copy.copy(self)
        if d.params is not None:
            d.params = copy.deepcopy(d.params)
        if d.fit_params is not None:
            d.fit_params = copy.deepcopy(d.fit_params)
        if finalize and not d.is_finalized():
            d.finalize()
        return d

    # helpers

    def has_roi(self) -> bool:
        head, tail = self.get_roi_margins()
        return head >= 0.0 and tail >= 0.0

    def is_multi_histogram(self) -> bool:
        return self.params.get("multi_histogram", False)

    def sweeps(self) -> int:
        if self.tdc_status is None:
            return 0
        return self.tdc_status.sweeps

    def _measurement_time_pg(self) -> float:
        if not self.has_params():
            return 0.0
        try:
            freq = float(self.params["instrument"]["pg_freq"])
            length = float(self.params["instrument"]["length"])
        except (KeyError, TypeError, ValueError):
            return 0.0
        if freq <= 0.0:
            return 0.0
        return self.sweeps() * length / freq

    def _measurement_time_tdc(self) -> float:
        trange = self.get_range()
        if trange is None:
            return 0.0
        return self.sweeps() * trange

    def measurement_time(self) -> float:
        """Calculate measurement time in sec.

        PG time and TDC time will be different because of eos_margin;
        PG time is closer to real measurement time and TDC time is a bit shorter than that.
        So, this function first tries to return PG time and fallback to TDC time.

        """

        t_pg = self._measurement_time_pg()
        if t_pg > 0.0:
            return t_pg
        return self._measurement_time_tdc()

    def has_raw_data(self) -> bool:
        """Return True if current data is valid (not empty nor all zero)."""

        return self.raw_data is not None and (self.raw_data > 0).any()

    def has_data(self) -> bool:
        partial = self.partial()
        N = self.num_pattern()

        if partial is not None and 0 <= partial < N:
            return (
                self._get_pattern_data(partial) is not None
                and self._get_pattern_ref(partial) is not None
            )
        else:
            return all(
                [
                    self._get_pattern_data(i) is not None and self._get_pattern_ref(i) is not None
                    for i in range(N)
                ]
            )

    def num_pattern(self) -> int:
        if not self.has_params():
            return 2
        return self.params.get("num_pattern", 2)

    def partial(self) -> int | None:
        if not self.has_params():
            return None
        return self.params.get("partial", -1)

    def is_partial(self) -> bool:
        p = self.partial()
        return p is not None and 0 <= p < self.num_pattern()

    def is_sweepN(self):
        return self.has_params() and is_sweepN(self.label)

    def is_CPlike(self) -> bool:
        return self.has_params() and is_CPlike(self.label)

    def is_correlation(self):
        return self.has_params() and is_correlation(self.label)

    def is_supersampling(self):
        return (
            self.label in ("xy8", "xy16")
            and "supersample" in self.params["pulse"]
            and self.params["pulse"]["supersample"] != 1
        )

    def can_resume(self, params: dict | None, label: str) -> bool:
        """Check if the measurement can be resumed with given new_params."""

        if self.label != label:
            return False
        if not self.has_params() or params is None:
            return False
        p0 = self.params.copy()
        p1 = params.copy()
        for p in (p0, p1):
            for k in (
                "instrument",
                "plot",
                "resume",
                "quick_resume",
                "sweeps",
                "duration",
                "num_pattern",
            ):
                if k in p:
                    del p[k]
        # parameters contains small float values (several nano-seconds: ~ 1e-9).
        # atol should be smaller than that.
        return dict_isclose(p0, p1, atol=1e-11)


def update_data(data: PODMRData):
    """update data to latest format"""

    if data.version() <= 0:
        # version 0 to 1
        ## tdc_status maybe raw tuple
        if data.tdc_status is not None:
            s = data.tdc_status
            data.tdc_status = TDCStatus(s[0], *s[2:])
        ## rename fit_param -> fit_params
        data.fit_params = data.fit_param
        del data.fit_param
        ## no None-initialization of fit_result
        if not hasattr(data, "fit_result"):
            data.fit_result = None
        ## rename param["trigger_length"] -> param["trigger_width"]
        data.params["trigger_width"] = data.params["trigger_length"]
        del data.params["trigger_length"]
        ## add missing attributes
        data._saved = True
        data.set_version(1)

    if data.version() <= 1:
        # version 1 to 2
        # store marker_indices as an array, instead of tuple of arrays.
        data.marker_indices = np.vstack(data.marker_indices)
        # fix bug of setting yunit = None
        if data.yunit is None:
            data.yunit = ""
        data.set_version(2)

    if data.version() <= 2:
        # version 2 to 3
        plot = data.params["plot"]
        if "xlogscale" in plot:
            plot["logX"] = plot["xlogscale"]
            del plot["xlogscale"]
        if "ylogscale" in plot:
            plot["logY"] = plot["ylogscale"]
            del plot["ylogscale"]
        data.set_version(3)

    if data.version() <= 3:
        # version 3 to 4
        ## newly added ROI-related params
        data.params["roi_head"] = -1.0e-9
        data.params["roi_tail"] = -1.0e-9
        data.set_version(4)

    if data.version() <= 4:
        # version 4 to 5
        data.label = data.params["method"]
        del data.params["method"]
        if data.fit_params:
            data.fit_label = data.fit_params["method"]
            del data.fit_params["method"]
        data.set_version(5)

    if data.version() <= 5:
        # version 5 to 6
        ## fixed param name
        if "invertsweep" in data.params:
            data.params["invert_sweep"] = data.params["invertsweep"]
            del data.params["invertsweep"]
        ## fixed location of optional pulse params
        ## here's only keys actually used for experiments before patch
        keys = [
            "90pulse",
            "180pulse",
            "tauconst",
            "Nconst",
            "readY",
            "invertY",
            "supersample",
            "flip_head",
        ]
        data.params["pulse"] = {}
        for k in keys:
            if k in data.params:
                data.params["pulse"][k] = data.params[k]
                del data.params[k]
        data.set_version(6)

    if data.version() <= 6:
        # version 6 to 7
        for n in ("data2", "data3", "data2ref", "data3ref"):
            if not hasattr(data, n):
                setattr(data, n, None)

        if data.has_params() and "num_pattern" not in data.params:
            data.params["num_pattern"] = 2
        data.set_version(7)

    if data.version() <= 7:
        # version 7 to 8
        if not hasattr(data, "laser_timing_offset"):
            data.laser_timing_offset = None
        data.set_version(8)
    return data
